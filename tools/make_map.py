"""Generates the ASANNI sample map illustration (original, decorative, not a real map).

Outputs the same drawing as:
  - an Android VectorDrawable  (asanni_location_map.xml)
  - an SVG                     (asanni_location_map.svg, for previews / the ui folder)
Usage: python3 make_map.py OUT_DIR
"""
import math
import os
import random
import sys

W, H = 360, 240
rnd = random.Random(7)

BG = "#E9E3D9"
BLOCK = "#E1DACE"
PARK = "#DCDDC9"
WATER = "#D3DEE0"
MINOR = "#F6F2EB"
MAJOR = "#D9A9A3"
MAJOR_CASE = "#F3EDE5"

shapes = []  # (kind, d, attrs)


def fill(d, color, alpha=1.0):
    shapes.append(("fill", d, {"color": color, "alpha": alpha}))


def stroke(d, color, width, alpha=1.0):
    shapes.append(("stroke", d, {"color": color, "width": width, "alpha": alpha}))


def f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


# background
fill(f"M0,0H{W}V{H}H0Z", BG)

# soft neighbourhood blocks
for _ in range(14):
    cx, cy = rnd.uniform(0, W), rnd.uniform(0, H)
    w, h = rnd.uniform(30, 70), rnd.uniform(20, 50)
    a = math.radians(-20)
    pts = []
    for dx, dy in ((-w, -h), (w, -h), (w, h), (-w, h)):
        x = cx + (dx * math.cos(a) - dy * math.sin(a)) / 2
        y = cy + (dx * math.sin(a) + dy * math.cos(a)) / 2
        pts.append((x, y))
    fill("M" + "L".join(f"{f(x)},{f(y)}" for x, y in pts) + "Z", BLOCK)

# parks
fill("M40,150 C55,138 85,140 92,156 C98,172 78,190 58,186 C38,182 28,162 40,150Z", PARK)
fill("M252,40 C268,32 296,38 300,54 C304,70 282,80 264,74 C246,68 240,48 252,40Z", PARK)

def grid(angle_deg, spacing, offset, width):
    a = math.radians(angle_deg)
    dx, dy = math.cos(a), math.sin(a)
    nx, ny = -dy, dx
    L = 600
    cx, cy = W / 2, H / 2
    k = -12
    while k <= 12:
        ox = cx + nx * (k * spacing + offset)
        oy = cy + ny * (k * spacing + offset)
        x1, y1 = ox - dx * L, oy - dy * L
        x2, y2 = ox + dx * L, oy + dy * L
        stroke(f"M{f(x1)},{f(y1)}L{f(x2)},{f(y2)}", MINOR, width)
        k += 1


# minor street grid, two directions
grid(-20, 19, 4, 1.4)
grid(70, 23, 9, 1.4)

# coastline / water (bottom-right), drawn over the grid so no streets run into the sea
fill(f"M{W},150 C330,158 312,176 300,196 C290,212 268,228 250,{H} L{W},{H}Z", WATER)

# major roads: pale casing + muted red centre (like the reference)
majors = [
    "M-10,70 C70,60 120,95 190,92 C250,89 300,60 370,66",
    "M120,-10 C128,50 150,110 176,150 C196,182 204,214 210,250",
    "M-10,200 C60,184 110,176 170,150 C220,128 270,124 370,118",
    "M300,-10 C290,40 270,80 240,110",
]
for d in majors:
    stroke(d, MAJOR_CASE, 6.5)
for d in majors:
    stroke(d, MAJOR, 3.2)


def write_vector(path):
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- [UI ASSET] ASANNI sample map illustration (original, decorative, NOT a real map).",
        "     Generated by tools/make_map.py. Replace by adding res/drawable-nodpi/asanni_location_map.png",
        "     (and deleting this file). The red pin and its pulse are separate views in the layout. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{W}dp"',
        f'    android:height="{H}dp"',
        f'    android:viewportWidth="{W}"',
        f'    android:viewportHeight="{H}">',
    ]
    for kind, d, a in shapes:
        if kind == "fill":
            out.append(f'    <path android:fillColor="{a["color"]}" android:pathData="{d}" />')
        else:
            out.append(
                f'    <path android:strokeColor="{a["color"]}" android:strokeWidth="{a["width"]}"'
                f' android:strokeLineCap="round" android:pathData="{d}" />'
            )
    out.append("</vector>")
    open(path, "w").write("\n".join(out) + "\n")


def write_svg(path):
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W*3}" height="{H*3}" viewBox="0 0 {W} {H}">']
    for kind, d, a in shapes:
        if kind == "fill":
            out.append(f'<path fill="{a["color"]}" d="{d}"/>')
        else:
            out.append(
                f'<path fill="none" stroke="{a["color"]}" stroke-width="{a["width"]}"'
                f' stroke-linecap="round" d="{d}"/>'
            )
    out.append("</svg>")
    open(path, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    out_dir = sys.argv[1]
    os.makedirs(out_dir, exist_ok=True)
    write_vector(os.path.join(out_dir, "asanni_location_map.xml"))
    write_svg(os.path.join(out_dir, "asanni_location_map.svg"))
    print(len(shapes), "paths")